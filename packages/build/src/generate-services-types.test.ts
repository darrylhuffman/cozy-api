import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { afterEach, beforeEach, describe, expect, it } from "vitest"
import { generateServicesTypes, renderProvidersDts } from "./generate-services-types.js"

describe("renderProvidersDts", () => {
  it("types each provider from its file's default export", () => {
    const out = renderProvidersDts([
      { name: "db", path: "providers/db.ts" },
      { name: "httpClient", path: "providers/http-client.ts" },
      { name: "s3-bucket", path: "providers/aws/s3.ts" },
    ])
    expect(out).toMatch(/declare module "@darrylondil\/lorien-runtime"/)
    expect(out).toMatch(/interface Services \{/)
    expect(out).toContain(`db: ProvidedValue<typeof import("../../providers/db.js").default>`)
    expect(out).toContain(
      `httpClient: ProvidedValue<typeof import("../../providers/http-client.js").default>`,
    )
    expect(out).toContain(
      `"s3-bucket": ProvidedValue<typeof import("../../providers/aws/s3.js").default>`,
    )
  })

  it("types legacy lorien.config.ts services as unknown", () => {
    const out = renderProvidersDts([], ["logger"])
    expect(out).toMatch(/logger: unknown/)
  })
})

describe("generateServicesTypes", () => {
  let dir: string

  beforeEach(() => {
    dir = mkdtempSync(join(tmpdir(), "lorien-types-"))
  })

  afterEach(() => {
    rmSync(dir, { recursive: true, force: true })
  })

  it("returns null path when there are no providers or services", async () => {
    const result = await generateServicesTypes(dir)
    expect(result.path).toBeNull()
    expect(result.serviceNames).toEqual([])
  })

  it("writes providers.d.ts from providers/ and lorien.config.ts, replacing services.d.ts", async () => {
    mkdirSync(join(dir, "providers", "db"), { recursive: true })
    writeFileSync(
      join(dir, "providers", "db.ts"),
      `export default defineProvider({ selector: "db", create: () => 1 })\n`,
    )
    writeFileSync(join(dir, "providers", "db", "open.ts"), "export {}\n")
    writeFileSync(join(dir, "providers", "db.test.ts"), "export {}\n")
    writeFileSync(
      join(dir, "lorien.config.ts"),
      `export default { target: "hono", services: { logger: {}, db: {} } }\n`,
    )
    const old = join(dir, ".lorien", "types", "services.d.ts")
    mkdirSync(join(dir, ".lorien", "types"), { recursive: true })
    writeFileSync(
      old,
      "// .lorien/types/services.d.ts (auto-generated by @darrylondil/lorien-build, do not edit)\n",
    )

    const result = await generateServicesTypes(dir)
    expect(result.path).toBe(join(dir, ".lorien", "types", "providers.d.ts"))
    expect(result.serviceNames).toEqual(["db", "logger"])
    const content = readFileSync(result.path!, "utf-8")
    expect(content).toMatch(/db: ProvidedValue/)
    expect(content).toMatch(/logger: unknown/)
    expect(existsSync(old)).toBe(false)
  })
})
