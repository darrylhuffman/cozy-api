import { mkdir, readFile, rm, writeFile } from "node:fs/promises"
import { dirname, join } from "node:path"
import {
  findProviderFiles,
  importLegacyServices,
  type ProviderFile,
} from "@darrylondil/lorien-runtime"

export interface GenerateResult {
  /** Where the .d.ts was written, or null when there is nothing to type. */
  path: string | null
  /** Names that were typed: providers first, then legacy services. */
  serviceNames: string[]
}

const HEADER = "auto-generated by @darrylondil/lorien-build, do not edit"

/**
 * Generates `.lorien/types/providers.d.ts`, typing each entry of `Services`
 * from its `providers/<name>.ts` file, so nodes get `db` with the exact type
 * its `create` returns. Services still in `lorien.config.ts` are typed
 * `unknown`. Idempotent.
 */
export async function generateServicesTypes(root: string): Promise<GenerateResult> {
  const providers = await findProviderFiles(root)
  const providerNames = new Set(providers.map((p) => p.name))
  const legacy = Object.keys(await importLegacyServices(root)).filter((n) => !providerNames.has(n))

  // The pre-providers file name; replaced by providers.d.ts.
  const oldPath = join(root, ".lorien", "types", "services.d.ts")
  try {
    if ((await readFile(oldPath, "utf-8")).includes(HEADER)) await rm(oldPath)
  } catch {
    // No old file.
  }

  if (providers.length === 0 && legacy.length === 0) {
    return { path: null, serviceNames: [] }
  }
  const outPath = join(root, ".lorien", "types", "providers.d.ts")
  await mkdir(dirname(outPath), { recursive: true })
  await writeFile(outPath, renderProvidersDts(providers, legacy), "utf-8")
  return { path: outPath, serviceNames: [...providers.map((p) => p.name), ...legacy] }
}

export function renderProvidersDts(providers: ProviderFile[], legacy: string[] = []): string {
  const lines: string[] = []
  lines.push(`// .lorien/types/providers.d.ts (${HEADER})`)
  lines.push(`import type { ProvidedValue } from "@darrylondil/lorien-runtime"`)
  lines.push("")
  lines.push(`declare module "@darrylondil/lorien-runtime" {`)
  lines.push("  interface Services {")
  for (const p of providers) {
    const spec = `../../${p.path.replace(/\.([mc]?)ts$/, ".$1js")}`
    lines.push(`    ${p.name}: ProvidedValue<typeof import("${spec}").default>`)
  }
  for (const name of legacy) {
    lines.push(
      `    ${name}: unknown // from lorien.config.ts; move it to providers/${name}.ts to type it`,
    )
  }
  lines.push("  }")
  lines.push("}")
  lines.push("")
  return lines.join("\n")
}

/** @deprecated Kept for callers of the pre-providers generator. */
export function renderServicesDts(serviceNames: string[]): string {
  return renderProvidersDts([], serviceNames)
}
