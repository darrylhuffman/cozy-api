import {
  dataDependencies,
  nodeDependencies,
  parseReference,
  parseWhen,
  type WorkflowFile,
  workflowRoutes,
} from "@darrylondil/lorien-runtime"

/**
 * Result of generating a single workflow's .gen.ts source.
 */
export interface EmitWorkflowResult {
  /** The generated TypeScript source. */
  source: string
  /** The user node `uses` strings imported by this workflow (e.g. "./nodes/foo"). */
  importedNodes: string[]
}

/**
 * Options for emitWorkflow.
 */
export interface EmitWorkflowOptions {
  /** The parsed workflow file. */
  workflow: WorkflowFile
  /**
   * Path under workflows/ (without `.workflow` extension), used to compute
   * the depth of the generated file. e.g. "users/create" or "users/[id]/get".
   * The generated file lives at "dist/workflows/<relPath>.gen.ts" so it walks
   * up `depth(relPath) + 1` (for "workflows/") directories to reach the
   * project root, where providers/ and nodes/ live.
   */
  relativePath: string
  /**
   * True when some provider is created per request (scoped, transient, or a
   * legacy factory service). Handlers then open a scope per request; otherwise
   * they read the boot-time singletons directly.
   */
  perRequestProviders?: boolean
  /**
   * Project-relative `_middleware.ts` files that guard this workflow,
   * outermost folder first (see `middlewareChain`). Each route runs them as
   * Hono middleware before the workflow.
   */
  middleware?: string[]
}

/**
 * Given a parsed workflow, emit the .gen.ts source string. It exports one
 * `run_<trigger>(trigger, services)` per @core/http-request trigger, holding
 * the workflow's logic with no Hono in it, and `register(app: Hono)`, which
 * mounts a thin route per trigger that calls it.
 *
 * The emitted code has zero @darrylondil/lorien-runtime imports. Only hono and the
 * user's own node modules are imported.
 */
export function emitWorkflow(opts: EmitWorkflowOptions): EmitWorkflowResult {
  const { workflow, relativePath } = opts

  // dist/workflows/<relativePath>.gen.ts → root is `dist/..`
  // Depth = number of path segments in relativePath (each is a parent dir to climb)
  //   + 1 for the "workflows/" parent that wraps every .gen.ts.
  const depth = relativePath.split("/").length + 1
  const upPrefix = "../".repeat(depth)
  const distPrefix = "../".repeat(depth - 1)
  const perRequest = opts.perRequestProviders ?? false
  const middleware = opts.middleware ?? []
  const guarded = middleware.length > 0

  // Collect all user-defined `uses` strings referenced by this workflow.
  const userUses = new Set<string>()
  for (const inst of Object.values(workflow.nodes)) {
    if (!inst.uses.startsWith("@core/")) {
      userUses.add(inst.uses)
    }
  }

  // Find all http-request triggers in this workflow.
  // `method` and `path` are literals under `values:`; the route is fixed at
  // build time. A missing path defaults to the workflow's folder.
  const triggers: TriggerInfo[] = workflowRoutes(workflow, `workflows/${relativePath}.workflow`)

  // Build a stable map from `uses` to local identifier.
  const sortedUses = [...userUses].sort()
  const usesToIdent = new Map<string, string>()
  const seenIdents = new Set<string>()
  for (const uses of sortedUses) {
    let ident = importIdentForUses(uses)
    // Collision-safety: append a counter if necessary.
    if (seenIdents.has(ident)) {
      let i = 2
      while (seenIdents.has(`${ident}${i}`)) i++
      ident = `${ident}${i}`
    }
    seenIdents.add(ident)
    usesToIdent.set(uses, ident)
  }

  const lines: string[] = []
  lines.push(`// AUTO-GENERATED by @darrylondil/lorien-build. Do not edit.`)
  lines.push(
    guarded
      ? `import type { Hono, Context, MiddlewareHandler, Next } from "hono"`
      : `import type { Hono, Context } from "hono"`,
  )
  lines.push(
    perRequest
      ? `import { openScope } from "${distPrefix}providers.gen.js"`
      : `import { singletons } from "${distPrefix}providers.gen.js"`,
  )
  for (const uses of sortedUses) {
    const ident = usesToIdent.get(uses)!
    const importPath = nodeImportPath(uses, upPrefix)
    lines.push(`import ${ident} from "${importPath}"`)
  }
  middleware.forEach((path, i) => {
    lines.push(`import mw${i} from "${upPrefix}${path.replace(/\.([mc]?)ts$/, ".$1js")}"`)
  })
  lines.push("")
  lines.push(renderTypes())
  lines.push("")
  lines.push(renderReadJsonBodyHelper())
  lines.push("")
  lines.push(renderCheckOutputHelper())
  if (triggers.some((t) => requestSourcedNodes(workflow, t.nodeId).size > 0)) {
    lines.push("")
    lines.push(renderParseInputHelper())
  }

  for (const trigger of triggers) {
    lines.push("")
    lines.push(...renderRun(workflow, trigger, usesToIdent))
  }

  lines.push("")
  lines.push(`export function register(app: Hono): void {`)
  if (guarded) lines.push(...renderGuards(middleware.length, perRequest))

  for (let i = 0; i < triggers.length; i++) {
    const trigger = triggers[i]!
    if (i > 0) lines.push("")
    lines.push(...renderRoute(trigger, perRequest, guarded))
  }

  lines.push(`}`)
  lines.push("")

  return {
    source: lines.join("\n"),
    importedNodes: sortedUses,
  }
}

const VARIABLE = "@core/variable"

interface TriggerInfo {
  nodeId: string
  path: string
  method: string
}

function renderReadJsonBodyHelper(): string {
  return [
    `/** Stands in for a JSON body that doesn't parse, so the route can answer 400. */`,
    `const INVALID_JSON = Symbol("invalid JSON")`,
    ``,
    `async function readJsonBody(c: Context): Promise<unknown> {`,
    `  const contentType = c.req.header("content-type") ?? ""`,
    `  if (contentType.includes("application/json")) {`,
    `    const text = await c.req.text()`,
    `    if (text.trim() === "") return null`,
    `    try {`,
    `      return JSON.parse(text)`,
    `    } catch {`,
    `      return INVALID_JSON`,
    `    }`,
    `  }`,
    `  if (c.req.raw.body) {`,
    `    try {`,
    `      return await c.req.text()`,
    `    } catch {`,
    `      return null`,
    `    }`,
    `  }`,
    `  return null`,
    `}`,
  ].join("\n")
}

function renderCheckOutputHelper(): string {
  return [
    `/** Stops at a node that returned something its outputs schema doesn't allow. */`,
    `function checkOutput(`,
    `  node: { outputs?: { safeParse(v: unknown): { success: boolean; error?: { issues: Array<{ path: PropertyKey[]; message: string }> } } } },`,
    `  nodeId: string,`,
    `  output: unknown,`,
    `): Record<string, unknown> {`,
    `  const checked = node.outputs?.safeParse(output)`,
    `  if (checked && !checked.success) {`,
    `    const issue = checked.error?.issues[0]`,
    `    const at = issue?.path.map(String).join(".") || "<root>"`,
    // biome-ignore lint/suspicious/noTemplateCurlyInString: emitted as-is into generated code.
    '    throw new Error(`Node \\`${nodeId}\\` failed: output doesn\'t match its outputs schema at \\`${at}\\`: ${issue?.message ?? "invalid"}`)',
    `  }`,
    `  return output as Record<string, unknown>`,
    `}`,
  ].join("\n")
}

function renderTypes(): string {
  return [
    `/** What an HTTP trigger hands the workflow: the parsed request. */`,
    `export interface HttpTrigger {`,
    `  body: unknown`,
    `  params: Record<string, string>`,
    `  query: Record<string, string>`,
    `  headers: Record<string, string>`,
    `  context: { requestId: string; timestamp: number }`,
    `}`,
    ``,
    `/** A workflow's result; the HTTP route turns it into a JSON Response. */`,
    `export interface WorkflowResult {`,
    `  status: number`,
    `  headers: Record<string, string>`,
    `  body: unknown`,
    `}`,
  ].join("\n")
}

/**
 * `run_<trigger>(trigger, services)`: the workflow's logic for one trigger,
 * with no Hono in it. Callers own the request and the provider lifetimes.
 */
function renderRun(
  workflow: WorkflowFile,
  trigger: TriggerInfo,
  usesToIdent: Map<string, string>,
): string[] {
  const lines: string[] = []

  const depsByNode = buildDepsByNode(workflow)
  const sliceIds = computeTriggerSlice(workflow, trigger.nodeId, depsByNode)

  // Project deps onto the slice for wave computation.
  const slicedDeps = new Map<string, Set<string>>()
  for (const id of sliceIds) {
    const filtered = new Set<string>()
    for (const d of depsByNode.get(id) ?? []) {
      if (sliceIds.has(d)) filtered.add(d)
    }
    slicedDeps.set(id, filtered)
  }
  const waves = computeWaves(slicedDeps)
  const ctx: RunContext = {
    workflow,
    usesToIdent,
    triggerId: trigger.nodeId,
    conditional: conditionalNodes(workflow, waves, trigger.nodeId),
  }
  const checksRequest = requestSourcedNodes(workflow, trigger.nodeId).size > 0

  const body: string[] = []
  body.push(`const ${outputsVar(trigger.nodeId)} = trigger`)
  // Variables are constants: their value is written straight into the code.
  const variableIds = [...sliceIds].filter((id) => workflow.nodes[id]?.uses === VARIABLE).sort()
  for (const id of variableIds) {
    const value = workflow.nodes[id]?.values?.value
    body.push(
      `const ${outputsVar(id)} = { value: ${value === undefined ? "undefined" : JSON.stringify(value)} }`,
    )
  }

  let waveNum = 0
  let returned = false
  for (const wave of waves) {
    const interesting = wave.filter(
      (id) => id !== trigger.nodeId && workflow.nodes[id]?.uses !== VARIABLE,
    )
    if (interesting.length === 0) continue
    waveNum++

    const responseIds = interesting.filter((id) => workflow.nodes[id]?.uses === "@core/response")
    const computeIds = interesting.filter((id) => workflow.nodes[id]?.uses !== "@core/response")

    if (computeIds.length === 1) {
      body.push("")
      body.push(`// Wave ${waveNum}: ${computeIds[0]}`)
      body.push(...renderSingleNodeCall(ctx, computeIds[0]!))
    } else if (computeIds.length > 1) {
      body.push("")
      body.push(`// Wave ${waveNum}: ${computeIds.join(", ")} (parallel)`)
      body.push(...renderParallelWave(ctx, computeIds))
    }

    // The first response in the wave that runs answers (sorted for determinism).
    for (const responseId of responseIds) {
      body.push("")
      body.push(
        ctx.conditional.has(responseId) ? `// Response ${responseId}, when it runs` : `// Response`,
      )
      body.push(...renderResponseReturn(ctx, responseId))
      if (!ctx.conditional.has(responseId)) {
        returned = true
        break
      }
    }
    if (returned) break
  }

  if (!returned) {
    // Every Response was skipped by its `when`: a missing branch, not a 200.
    const responses = [...sliceIds]
      .filter((id) => workflow.nodes[id]?.uses === "@core/response")
      .sort()
    const message =
      responses.length > 0
        ? `no Response node ran (skipped: ${responses.join(", ")}); add a Response for this case`
        : "the workflow has no Response node"
    body.push("")
    body.push(`throw new Error(${JSON.stringify(message)})`)
  }

  lines.push(`/** ${trigger.method} ${trigger.path} */`)
  lines.push(
    `export async function ${runFnName(trigger.nodeId)}(trigger: HttpTrigger, services: unknown): Promise<WorkflowResult> {`,
  )
  if (checksRequest) {
    // A bad value from the request is the client's mistake: answer 400.
    lines.push(`  try {`)
    lines.push(...body.map((l) => (l ? `    ${l}` : l)))
    lines.push(`  } catch (e) {`)
    lines.push(`    if (e instanceof InvalidRequest) return e.result`)
    lines.push(`    throw e`)
    lines.push(`  }`)
  } else {
    lines.push(...body.map((l) => (l ? `  ${l}` : l)))
  }
  lines.push(`}`)
  return lines
}

/** The Hono route for one trigger: read the request, call its run function, send JSON. */
function renderRoute(trigger: TriggerInfo, perRequest: boolean, guarded: boolean): string[] {
  const lines: string[] = []

  // Hono runs every handler registered for a route in order, so the guards
  // registered first act as this route's middleware.
  if (guarded)
    lines.push(
      `  for (const guard of guards) app.on("${trigger.method}", "${trigger.path}", guard)`,
    )
  lines.push(
    `  app.on("${trigger.method}", "${trigger.path}", async (c: Context): Promise<Response> => {`,
  )
  // With middleware, the scope (and request id) is opened by the first guard.
  const scopeFromGuard = guarded && perRequest
  lines.push(
    scopeFromGuard
      ? `    const requestId = c.get("lorien.requestId" as never) as string`
      : `    const requestId = crypto.randomUUID()`,
  )
  lines.push(`    const body = await readJsonBody(c)`)
  lines.push(`    if (body === INVALID_JSON) {`)
  lines.push(
    `      return c.json({ error: "Invalid request", issues: [{ path: "body", message: "Body is not valid JSON" }] }, 400)`,
  )
  lines.push(`    }`)
  lines.push(`    const trigger: HttpTrigger = {`)
  lines.push(`      body,`)
  lines.push(`      params: c.req.param(),`)
  lines.push(`      query: Object.fromEntries(new URL(c.req.url).searchParams.entries()),`)
  lines.push(`      headers: Object.fromEntries(c.req.raw.headers.entries()),`)
  lines.push(`      context: { requestId, timestamp: Date.now() },`)
  lines.push(`    }`)

  const run = runFnName(trigger.nodeId)
  if (!perRequest) {
    lines.push(`    const result = await ${run}(trigger, singletons)`)
  } else if (scopeFromGuard) {
    lines.push(`    const result = await ${run}(trigger, c.get("lorien.providers" as never))`)
  } else {
    // Run in a provider scope, disposed once the workflow is done.
    lines.push(`    const scope = await openScope({ requestId, timestamp: Date.now() })`)
    lines.push(`    let result: WorkflowResult`)
    lines.push(`    try {`)
    lines.push(`      result = await ${run}(trigger, scope.values)`)
    lines.push(`    } finally {`)
    lines.push(`      void scope.dispose()`)
    lines.push(`    }`)
  }

  // c.newResponse keeps headers middleware set with c.header() before next().
  lines.push(`    return c.newResponse(`)
  lines.push(`      result.body === undefined ? "null" : JSON.stringify(result.body),`)
  lines.push(`      result.status as never,`)
  lines.push(`      { "content-type": "application/json", ...result.headers },`)
  lines.push(`    )`)
  lines.push(`  })`)
  return lines
}

/**
 * `guards`: the Hono middleware every route in this file runs first. With
 * per-request providers, the first one opens the request's scope so
 * middleware and nodes share it.
 */
function renderGuards(count: number, perRequest: boolean): string[] {
  const mws = Array.from({ length: count }, (_, i) => `mw${i}`).join(", ")
  const lines = [
    `  // _middleware.ts, outermost folder first`,
    `  const middleware = [${mws}].flat()`,
  ]
  if (!perRequest) {
    lines.push(
      `  const guards: MiddlewareHandler[] = middleware.map(`,
      `    (m) => async (c: Context, next: Next) => m.run(c, next, singletons as never),`,
      `  )`,
    )
    return lines
  }
  lines.push(
    `  const guards: MiddlewareHandler[] = [`,
    `    async (c: Context, next: Next) => {`,
    `      const requestId = crypto.randomUUID()`,
    `      const scope = await openScope({ requestId, timestamp: Date.now() })`,
    `      c.set("lorien.requestId" as never, requestId as never)`,
    `      c.set("lorien.providers" as never, scope.values as never)`,
    `      try {`,
    `        await next()`,
    `      } finally {`,
    `        void scope.dispose()`,
    `      }`,
    `    },`,
    `    ...middleware.map(`,
    `      (m) => async (c: Context, next: Next) =>`,
    `        m.run(c, next, c.get("lorien.providers" as never) as never),`,
    `    ),`,
    `  ]`,
  )
  return lines
}

interface RunContext {
  workflow: WorkflowFile
  usesToIdent: Map<string, string>
  triggerId: string
  /** Nodes that may be skipped: they have a `when`, or read a node that may be. */
  conditional: Set<string>
}

/** `<schema>.parse(...)`, or `parseInput(...)` when some of the input comes from the request. */
function renderParse(ctx: RunContext, nodeId: string, ident: string, inputExpr: string): string {
  const sources = requestSources(ctx.workflow, nodeId, ctx.triggerId)
  return sources === null
    ? `${ident}.inputs.parse(${inputExpr})`
    : `parseInput(${ident}.inputs, ${inputExpr}, ${JSON.stringify(sources)})`
}

function identFor(ctx: RunContext, nodeId: string): string {
  const uses = ctx.workflow.nodes[nodeId]!.uses
  const ident = ctx.usesToIdent.get(uses)
  if (!ident) throw new Error(`emit-workflow: no identifier for uses \`${uses}\``)
  return ident
}

function renderSingleNodeCall(ctx: RunContext, nodeId: string): string[] {
  const inst = ctx.workflow.nodes[nodeId]!
  const ident = identFor(ctx, nodeId)
  const outVar = outputsVar(nodeId)
  const inputVar = `_${nodeId}Input`
  const inputRawVar = `_${nodeId}InputRaw`
  const inputExpr = renderInputExpr(inst.in, inst.values)

  // A node that may be skipped runs (and parses its input) only when it runs;
  // skipped, it has no outputs.
  if (ctx.conditional.has(nodeId)) {
    const ran = ranVar(nodeId)
    return [
      `const ${ran} = ${renderRanExpr(ctx, nodeId)}`,
      `const ${outVar} = (${ran}`,
      `  ? checkOutput(${ident}, "${nodeId}", await ${ident}.run(`,
      `      ${renderParse(ctx, nodeId, ident, inputExpr)} as never,`,
      `      services as never,`,
      `      undefined as never,`,
      `    ))`,
      `  : {}) as Record<string, unknown>`,
    ]
  }

  // Whole-object form: source is a reference expression (already a JS access
  // chain). Emit a raw alias for clarity, then run through inputs.parse().
  if (typeof inst.in === "string") {
    return [
      `const ${inputRawVar} = ${inputExpr}`,
      `const ${inputVar} = ${renderParse(ctx, nodeId, ident, inputRawVar)}`,
      `const ${outVar} = checkOutput(${ident}, "${nodeId}", await ${ident}.run(`,
      `  ${inputVar} as never,`,
      `  services as never,`,
      `  undefined as never,`,
      `))`,
    ]
  }

  return [
    `const ${inputVar} = ${renderParse(ctx, nodeId, ident, inputExpr)}`,
    `const ${outVar} = checkOutput(${ident}, "${nodeId}", await ${ident}.run(`,
    `  ${inputVar} as never,`,
    `  services as never,`,
    `  undefined as never,`,
    `))`,
  ]
}

function renderParallelWave(ctx: RunContext, nodeIds: string[]): string[] {
  const lines: string[] = []
  // Emit inputs.parse() for each node before the allSettled block.
  for (const id of nodeIds) {
    const inst = ctx.workflow.nodes[id]!
    const parse = renderParse(ctx, id, identFor(ctx, id), renderInputExpr(inst.in, inst.values))
    if (ctx.conditional.has(id)) {
      lines.push(`const ${ranVar(id)} = ${renderRanExpr(ctx, id)}`)
      lines.push(`const _${id}Input = ${ranVar(id)} ? ${parse} : undefined`)
    } else {
      lines.push(`const _${id}Input = ${parse}`)
    }
  }
  const settledNames = nodeIds.map((id) => `${id}_settled`)
  lines.push(`const [${settledNames.join(", ")}] = await Promise.allSettled([`)
  for (const id of nodeIds) {
    const ident = identFor(ctx, id)
    const call = `${ident}.run(_${id}Input as never, services as never, undefined as never).then((o: unknown) => checkOutput(${ident}, "${id}", o))`
    lines.push(ctx.conditional.has(id) ? `  ${ranVar(id)} ? ${call} : {},` : `  ${call},`)
  }
  lines.push(`])`)
  lines.push(`const _rejection = [${settledNames.join(", ")}].find((r) => r.status === "rejected")`)
  lines.push(`if (_rejection) throw (_rejection as PromiseRejectedResult).reason`)
  for (const id of nodeIds) {
    lines.push(
      `const ${outputsVar(id)} = (${id}_settled as PromiseFulfilledResult<unknown>).value as Record<string, unknown>`,
    )
  }
  return lines
}

function renderResponseReturn(ctx: RunContext, nodeId: string): string[] {
  const inst = ctx.workflow.nodes[nodeId]!

  let bodyExpr: string
  let statusExpr: string
  let headersExpr: string

  if (typeof inst.in === "string") {
    // Whole-object form: the resolved value is the input bag itself; pluck
    // body/status/headers fields off it directly. `values:` is ignored here.
    const base = renderInputExpr(inst.in, inst.values)
    bodyExpr = `(${base})?.body`
    statusExpr = `(${base})?.status`
    headersExpr = `(${base})?.headers`
  } else {
    // Per-field: references in `in:` win over literals in `values:`.
    const inMap = inst.in ?? {}
    const values = (inst.values ?? {}) as Record<string, unknown>
    bodyExpr =
      "body" in inMap
        ? renderReferenceValue(inMap.body)
        : "body" in values
          ? renderJsonLiteral(values.body)
          : `null`
    statusExpr =
      "status" in inMap
        ? renderReferenceValue(inMap.status)
        : "status" in values
          ? renderJsonLiteral(values.status)
          : `200`
    headersExpr =
      "headers" in inMap
        ? renderReferenceValue(inMap.headers)
        : "headers" in values
          ? renderJsonLiteral(values.headers)
          : `{}`
  }

  const ret = [
    `return {`,
    `  status: ((${statusExpr}) as number | undefined) ?? 200,`,
    `  headers: ((${headersExpr}) as Record<string, string> | undefined) ?? {},`,
    `  body: ${bodyExpr},`,
    `}`,
  ]
  if (!ctx.conditional.has(nodeId)) return ret
  return [`if (${renderRanExpr(ctx, nodeId)}) {`, ...ret.map((l) => `  ${l}`), `}`]
}

function ranVar(nodeId: string): string {
  return `${nodeId.replace(/[^a-zA-Z0-9_$]/g, "_")}_ran`
}

/**
 * Whether a conditional node runs: every conditional node it reads ran, and
 * its `when` holds. Mirrors the interpreter's skip rule.
 */
function renderRanExpr(ctx: RunContext, nodeId: string): string {
  const inst = ctx.workflow.nodes[nodeId]!
  const parts = dataDependencies(inst)
    .filter((d) => ctx.conditional.has(d))
    .sort()
    .map(ranVar)
  const when = inst.when !== undefined ? parseWhen(inst.when) : null
  if (when) {
    const chain = outputsVar(when.ref.nodeId) + accessChain(when.ref.path)
    parts.push(when.negate ? `!${chain}` : `Boolean(${chain})`)
  }
  return parts.length > 0 ? parts.join(" && ") : "true"
}

/** Nodes that may be skipped at run time, found in wave order. */
function conditionalNodes(
  workflow: WorkflowFile,
  waves: string[][],
  triggerId: string,
): Set<string> {
  const out = new Set<string>()
  for (const wave of waves) {
    for (const id of wave) {
      const inst = workflow.nodes[id]
      if (!inst || id === triggerId || inst.uses === VARIABLE) continue
      if (inst.when !== undefined || dataDependencies(inst).some((d) => out.has(d))) out.add(id)
    }
  }
  return out
}

/**
 * Where a node's input comes from the request, located in the request: a
 * field name → "query.minCapacity" map, or one prefix ("body") when the whole
 * input is a request value. Null when none of it does.
 */
function requestSources(
  workflow: WorkflowFile,
  nodeId: string,
  triggerId: string,
): string | Record<string, string> | null {
  const inst = workflow.nodes[nodeId]
  if (!inst || inst.in === undefined) return null
  if (typeof inst.in === "string") {
    const ref = parseReference(inst.in)
    return ref?.nodeId === triggerId ? ref.path.join(".") : null
  }
  const out: Record<string, string> = {}
  for (const [field, raw] of Object.entries(inst.in)) {
    const ref = parseReference(raw)
    if (ref?.nodeId === triggerId) out[field] = ref.path.join(".")
  }
  return Object.keys(out).length > 0 ? out : null
}

/** User nodes that read part of their input straight from this trigger. */
function requestSourcedNodes(workflow: WorkflowFile, triggerId: string): Set<string> {
  const out = new Set<string>()
  for (const [id, inst] of Object.entries(workflow.nodes)) {
    if (inst.uses.startsWith("@core/")) continue
    if (requestSources(workflow, id, triggerId) !== null) out.add(id)
  }
  return out
}

function renderParseInputHelper(): string {
  return [
    `/** A request value failed a node's schema; the route answers 400 with the issues. */`,
    `class InvalidRequest extends Error {`,
    `  constructor(readonly issues: Array<{ path: string; message: string }>) {`,
    `    super("Invalid request")`,
    `  }`,
    `  get result(): WorkflowResult {`,
    `    return { status: 400, headers: {}, body: { error: "Invalid request", issues: this.issues } }`,
    `  }`,
    `}`,
    ``,
    `interface InputSchema {`,
    `  safeParse(input: unknown): {`,
    `    success: boolean`,
    `    data?: unknown`,
    `    error?: { issues: Array<{ path: PropertyKey[]; message: string }> }`,
    `  }`,
    `}`,
    ``,
    `/**`,
    ` * Parses a node's input. Issues on values from the request become an`,
    ` * InvalidRequest (400); anything else is a bug and throws as usual.`,
    ` */`,
    `function parseInput(`,
    `  schema: InputSchema,`,
    `  input: unknown,`,
    `  fromRequest: string | Record<string, string>,`,
    `): unknown {`,
    `  const result = schema.safeParse(input)`,
    `  if (result.success) return result.data`,
    `  const issues: Array<{ path: string; message: string }> = []`,
    `  for (const issue of result.error?.issues ?? []) {`,
    `    const path = issue.path.map(String)`,
    `    const base = typeof fromRequest === "string" ? fromRequest : fromRequest[path[0] ?? ""]`,
    `    if (base === undefined) continue`,
    `    const rest = typeof fromRequest === "string" ? path : path.slice(1)`,
    `    issues.push({ path: [base, ...rest].filter(Boolean).join("."), message: issue.message })`,
    `  }`,
    `  if (issues.length > 0) throw new InvalidRequest(issues)`,
    `  throw result.error`,
    `}`,
  ].join("\n")
}

/**
 * Render the per-field input object for `inputs.parse(...)`. Combines literal
 * values from `values:` (the floor) with reference overrides from `in:`.
 */
function renderInputObject(
  inMap: Record<string, string> | undefined,
  values: Record<string, unknown> | undefined,
): string {
  // Merge keys: values first, then in: (which can override). Maintain key
  // insertion order — values keys first, then in: keys that weren't in values.
  const merged = new Map<string, string>()
  if (values) {
    for (const [k, v] of Object.entries(values)) {
      merged.set(k, renderJsonLiteral(v))
    }
  }
  if (inMap) {
    for (const [k, v] of Object.entries(inMap)) {
      merged.set(k, renderReferenceValue(v))
    }
  }
  if (merged.size === 0) return `{}`
  const parts: string[] = []
  for (const [k, expr] of merged) {
    parts.push(`${jsKey(k)}: ${expr}`)
  }
  return `{ ${parts.join(", ")} }`
}

/**
 * Render `in:` of either form (string reference for whole-object, or per-field
 * object) as a JS expression suitable for passing to `inputs.parse(...)`.
 */
function renderInputExpr(
  inField: string | Record<string, string> | undefined,
  values: Record<string, unknown> | undefined,
): string {
  if (typeof inField === "string") {
    // Whole-object reference: literals under `values:` are ignored.
    return renderReferenceValue(inField)
  }
  return renderInputObject(inField, values)
}

/**
 * Render a reference string from `in:` as a JS access-chain expression.
 * The string MUST be a valid reference — `in:` is references-only.
 */
function renderReferenceValue(raw: unknown): string {
  if (typeof raw !== "string") {
    throw new Error(`emit-workflow: \`in:\` value must be a reference string, got ${typeof raw}`)
  }
  const ref = parseReference(raw)
  if (!ref) {
    throw new Error(`emit-workflow: not a valid node reference: ${JSON.stringify(raw)}`)
  }
  const { nodeId, path } = ref
  const base = outputsVar(nodeId)
  if (path.length === 0) return base
  // Optional chaining, like the interpreter: a missing body or field reads as
  // undefined and fails the node's input schema instead of throwing.
  return base + accessChain(path)
}

/** `?.a?.b`, with `?.["x-api-key"]` for a field that isn't a JS identifier. */
function accessChain(path: string[]): string {
  return path
    .map((seg) => (/^[a-zA-Z_$][\w$]*$/.test(seg) ? `?.${seg}` : `?.[${JSON.stringify(seg)}]`))
    .join("")
}

/**
 * Render an arbitrary JSON-serializable value as a JS literal expression.
 */
function renderJsonLiteral(value: unknown): string {
  if (value === undefined) return `undefined`
  if (value === null) return `null`
  if (typeof value === "string") return JSON.stringify(value)
  if (typeof value === "number" || typeof value === "boolean") return String(value)
  if (typeof value === "bigint") return `${value.toString()}n`
  if (Array.isArray(value)) {
    return `[${value.map(renderJsonLiteral).join(", ")}]`
  }
  if (typeof value === "object") {
    const entries = Object.entries(value as Record<string, unknown>)
    if (entries.length === 0) return `{}`
    return `{ ${entries.map(([k, v]) => `${jsKey(k)}: ${renderJsonLiteral(v)}`).join(", ")} }`
  }
  return `null`
}

function jsKey(key: string): string {
  if (/^[a-zA-Z_$][\w$]*$/.test(key)) return key
  return JSON.stringify(key)
}

function nodeImportPath(uses: string, upPrefix: string): string {
  const cleaned = uses.startsWith("./") ? uses.slice(2) : uses
  return `${upPrefix}${cleaned}.js`
}

function importIdentForUses(uses: string): string {
  const base = uses.split("/").pop() ?? uses
  const parts = base.split("-").filter((s) => s.length > 0)
  if (parts.length === 0) return "node_default"
  const [first, ...rest] = parts
  const ident = first! + rest.map((p) => p[0]!.toUpperCase() + p.slice(1)).join("")
  if (!/^[a-zA-Z_$]/.test(ident)) return `_${ident}`
  return ident
}

function runFnName(nodeId: string): string {
  return `run_${nodeId.replace(/[^a-zA-Z0-9_$]/g, "_")}`
}

function outputsVar(nodeId: string): string {
  if (/^[a-zA-Z_$][\w$]*$/.test(nodeId)) return `${nodeId}_outputs`
  const safe = nodeId.replace(/[^a-zA-Z0-9_$]/g, "_")
  return `${safe}_outputs`
}

// --- Graph helpers (mirror runtime's logic, kept local so codegen doesn't
//     have to import runtime internals).

function buildDepsByNode(wf: WorkflowFile): Map<string, Set<string>> {
  const depsByNode = new Map<string, Set<string>>()
  for (const [id, inst] of Object.entries(wf.nodes)) {
    depsByNode.set(id, new Set(nodeDependencies(inst).filter((d) => wf.nodes[d])))
  }
  return depsByNode
}

function computeWaves(depsByNode: Map<string, Set<string>>): string[][] {
  const remaining = new Map<string, Set<string>>()
  for (const [id, deps] of depsByNode) {
    remaining.set(id, new Set(deps))
  }
  const waves: string[][] = []
  while (remaining.size > 0) {
    const wave: string[] = []
    for (const [id, deps] of remaining) {
      if (deps.size === 0) wave.push(id)
    }
    if (wave.length === 0) {
      throw new Error("computeWaves: stuck (possible cycle — validate first)")
    }
    wave.sort()
    waves.push(wave)
    for (const id of wave) {
      remaining.delete(id)
      for (const deps of remaining.values()) deps.delete(id)
    }
  }
  return waves
}

function computeTriggerSlice(
  wf: WorkflowFile,
  triggerNodeId: string,
  depsByNode: Map<string, Set<string>>,
): Set<string> {
  const allIds = Object.keys(wf.nodes)
  const downstreamOf = new Map<string, Set<string>>()
  for (const id of allIds) downstreamOf.set(id, new Set())
  for (const [id, deps] of depsByNode) {
    for (const d of deps) downstreamOf.get(d)?.add(id)
  }

  const allTriggers = allIds.filter((id) => wf.nodes[id]?.uses === "@core/http-request")
  const reachableFrom = new Map<string, Set<string>>()
  for (const tid of allTriggers) {
    const reach = new Set<string>([tid])
    const q = [tid]
    while (q.length > 0) {
      const cur = q.shift()!
      for (const n of downstreamOf.get(cur) ?? []) {
        if (!reach.has(n)) {
          reach.add(n)
          q.push(n)
        }
      }
    }
    reachableFrom.set(tid, reach)
  }

  const ownedByAny = new Set<string>()
  for (const r of reachableFrom.values()) for (const id of r) ownedByAny.add(id)

  const myReach = reachableFrom.get(triggerNodeId) ?? new Set([triggerNodeId])
  const hasExplicitResponse = [...myReach].some(
    (id) => id !== triggerNodeId && wf.nodes[id]?.uses === "@core/response",
  )

  const included = new Set<string>()
  for (const id of allIds) {
    if (myReach.has(id)) {
      included.add(id)
    } else if (!ownedByAny.has(id)) {
      const isResponse = wf.nodes[id]?.uses === "@core/response"
      if (!isResponse || !hasExplicitResponse) included.add(id)
    }
  }
  return included
}
