describe("emitWorkflow — parallel waves", () => {
  it("uses plain await for single-node waves", () => {
    const { source } = emitWorkflow({
      workflow: wf({
        lorien: 1,
        nodes: {
          req: {
            uses: "@core/http-request",
            values: { path: "/", method: "GET" },
          },
          a: { uses: "./nodes/foo", in: {} },
          res: { uses: "@core/response", in: { body: "a.value" } },
        },
      }),
      relativePath: "x",
    })
    // inputs.parse() is called before run()
    expect(source).toMatch(/const _aInput = foo\.inputs\.parse\(\{\}\)/)
    expect(source).toMatch(/const a_outputs = checkOutput\(foo, "a", await foo\.run\(/)
    expect(source).not.toMatch(/Promise\.allSettled/)
  })

  it("uses Promise.allSettled for two parallel siblings", () => {
    const { source } = emitWorkflow({
      workflow: wf({
        lorien: 1,
        nodes: {
          req: {
            uses: "@core/http-request",
            values: { path: "/", method: "GET" },
          },
          a: { uses: "./nodes/foo", in: { x: "req.body" } },
          b: { uses: "./nodes/bar", in: { x: "req.body" } },
          res: { uses: "@core/response", in: { body: "a.value" } },
        },
      }),
      relativePath: "x",
    })
    // inputs.parse() is called for each parallel node before allSettled
    expect(source).toMatch(
      /const _aInput = parseInput\(foo\.inputs, \{ x: req_outputs\?\.body \}, \{"x":"body"\}\)/,
    )
    expect(source).toMatch(
      /const _bInput = parseInput\(bar\.inputs, \{ x: req_outputs\?\.body \}, \{"x":"body"\}\)/,
    )
    expect(source).toMatch(/Promise\.allSettled\(\[/)
    expect(source).toMatch(/a_settled/)
    expect(source).toMatch(/b_settled/)
    expect(source).toMatch(
      /if \(_rejection\) throw \(_rejection as PromiseRejectedResult\)\.reason/,
    )
  })
})

