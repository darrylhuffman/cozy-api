import type { ProviderLifetime } from "@darrylondil/lorien-runtime"

export interface EmitProviderInfo {
  /** The name nodes read it by, e.g. "db". */
  name: string
  /** Project-relative source path, e.g. "providers/db.ts". */
  path: string
  lifetime: ProviderLifetime
  uses: readonly string[]
  hasEnv: boolean
  hasDispose: boolean
}

export interface EmitProvidersOptions {
  /** Providers in creation order (see `planProviders`). */
  providers: EmitProviderInfo[]
  /** Legacy `lorien.config.ts` services: plain values and per-request factories. */
  legacy?: { values: string[]; factories: string[] }
}

export interface EmitProvidersResult {
  source: string
  /** Whether handlers must open a scope per request (see `openScope`). */
  perRequest: boolean
}

/**
 * Emits `dist/providers.gen.ts`: static imports of every provider, the
 * singletons created once at module load, and — only when something is
 * created per request — an `openScope` function. No container, registry or
 * lorien runtime import: this is the wiring a person would write by hand.
 */
export function emitProviders(opts: EmitProvidersOptions): EmitProvidersResult {
  const providers = opts.providers
  const legacyValues = opts.legacy?.values ?? []
  const legacyFactories = opts.legacy?.factories ?? []
  const hasLegacy = legacyValues.length + legacyFactories.length > 0
  const ident = (name: string) => `provider_${name}`
  const perRequestProviders = providers.filter((p) => p.lifetime !== "singleton")
  const perRequest = perRequestProviders.length > 0 || legacyFactories.length > 0

  const lines: string[] = []
  lines.push(`// AUTO-GENERATED by @darrylondil/lorien-build. Do not edit.`)
  if (hasLegacy) lines.push(`import config from "../lorien.config.js"`)
  for (const p of providers) {
    lines.push(`import ${ident(p.name)} from "../${p.path.replace(/\.[mc]?ts$/, ".js")}"`)
  }
  lines.push("")
  lines.push(`type Request = { requestId: string; timestamp: number }`)
  lines.push(`type Create = (context: unknown) => unknown`)

  const withEnv = providers.filter((p) => p.hasEnv)
  if (withEnv.length > 0) {
    lines.push("")
    lines.push(`// Environment, validated once at boot.`)
    lines.push(`const envProblems: string[] = []`)
    lines.push(`function readEnv(name: string, schema: unknown): unknown {`)
    lines.push(
      `  const result = (schema as { safeParse(v: unknown): { success: boolean; data?: unknown; error?: { issues: { path: PropertyKey[]; message: string }[] } } }).safeParse(process.env)`,
    )
    lines.push(`  if (result.success) return result.data`)
    lines.push(`  for (const issue of result.error?.issues ?? []) {`)
    lines.push(
      `    envProblems.push(\`  \${name}: \${issue.path.join(".") || "(env)"}: \${issue.message}\`)`,
    )
    lines.push(`  }`)
    lines.push(`  return undefined`)
    lines.push(`}`)
    for (const p of withEnv) {
      lines.push(`const env_${p.name} = readEnv("${p.name}", ${ident(p.name)}.env)`)
    }
    lines.push(`if (envProblems.length > 0) {`)
    lines.push(
      `  throw new Error(\`[lorien] provider environment is invalid:\\n\${envProblems.join("\\n")}\`)`,
    )
    lines.push(`}`)
  }
  const envOf = (p: EmitProviderInfo) => (p.hasEnv ? `env_${p.name}` : "undefined")
  const depsOf = (p: EmitProviderInfo, from: string) =>
    p.uses.length === 0
      ? "{}"
      : `{ ${p.uses.map((u) => `${JSON.stringify(u)}: ${from}[${JSON.stringify(u)}]`).join(", ")} }`
  const createCall = (p: EmitProviderInfo, from: string, request: string) =>
    `(${ident(p.name)}.create as Create)({ env: ${envOf(p)}, providers: ${depsOf(p, from)}, request: ${request} })`

  lines.push("")
  lines.push(`// Singletons, created once at boot in dependency order.`)
  lines.push(`export const singletons: Record<string, unknown> = {}`)
  if (hasLegacy) {
    lines.push(`const legacy = (config.services ?? {}) as Record<string, unknown>`)
    for (const name of legacyValues) {
      lines.push(`singletons[${JSON.stringify(name)}] = legacy[${JSON.stringify(name)}]`)
    }
  }
  for (const p of providers) {
    if (p.lifetime !== "singleton") continue
    lines.push(
      `singletons[${JSON.stringify(p.name)}] = await ${createCall(p, "singletons", "null")}`,
    )
  }

  const disposable = providers.filter((p) => p.lifetime === "singleton" && p.hasDispose)
  lines.push("")
  lines.push(`/** Disposes the singletons, last created first. */`)
  lines.push(`export async function disposeSingletons(): Promise<void> {`)
  for (const p of [...disposable].reverse()) {
    lines.push(
      `  await Promise.resolve(${ident(p.name)}.dispose?.(singletons[${JSON.stringify(p.name)}] as never)).catch(reportDisposeError)`,
    )
  }
  lines.push(`}`)
  lines.push("")
  lines.push(`function reportDisposeError(e: unknown): void {`)
  lines.push(
    `  console.error(\`[lorien] disposing a provider failed: \${e instanceof Error ? e.message : String(e)}\`)`,
  )
  lines.push(`}`)

  if (perRequest) {
    lines.push("")
    lines.push(`/** Creates this request's scoped providers; transient ones on every read. */`)
    lines.push(
      `export async function openScope(request: Request): Promise<{ values: Record<string, unknown>; dispose(): Promise<void> }> {`,
    )
    lines.push(`  const values: Record<string, unknown> = { ...singletons }`)
    lines.push(`  const created: Array<() => unknown> = []`)
    for (const name of legacyFactories) {
      const key = JSON.stringify(name)
      lines.push(`  values[${key}] = await (legacy[${key}] as (r: Request) => unknown)(request)`)
    }
    for (const p of providers) {
      if (p.lifetime === "scoped") {
        const v = `scoped_${p.name}`
        lines.push(`  const ${v} = await ${createCall(p, "values", "request")}`)
        lines.push(`  values[${JSON.stringify(p.name)}] = ${v}`)
        if (p.hasDispose) {
          lines.push(`  created.push(() => ${ident(p.name)}.dispose?.(${v} as never))`)
        }
      } else if (p.lifetime === "transient") {
        lines.push(`  Object.defineProperty(values, ${JSON.stringify(p.name)}, {`)
        lines.push(`    enumerable: true,`)
        lines.push(`    get() {`)
        lines.push(`      const value = ${createCall(p, "values", "request")}`)
        if (p.hasDispose) {
          lines.push(`      created.push(() => ${ident(p.name)}.dispose?.(value as never))`)
        }
        lines.push(`      return value`)
        lines.push(`    },`)
        lines.push(`  })`)
      }
    }
    lines.push(`  return {`)
    lines.push(`    values,`)
    lines.push(`    async dispose() {`)
    lines.push(`      for (const d of created.reverse()) {`)
    lines.push(`        await Promise.resolve().then(d).catch(reportDisposeError)`)
    lines.push(`      }`)
    lines.push(`    },`)
    lines.push(`  }`)
    lines.push(`}`)
  }
  lines.push("")

  return { source: lines.join("\n"), perRequest }
}
